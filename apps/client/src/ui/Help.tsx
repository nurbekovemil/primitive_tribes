export function Help() {
  const [open, setOpen] = useState(() => {
    try {
      return localStorage.getItem('helpHidden') !== '1';
    } catch {
      return true;
    }
  });
  const toggle = () => {
    setOpen(!open);
    try {
      localStorage.setItem('helpHidden', open ? '1' : '0');
    } catch {
      /* без хранилища панель просто откроется снова */
    }
  };
  return (
    <div className="panel help">
      <button className="toggle" onClick={toggle}>
        {open ? '✖ Скрыть' : '❓ Управление'}
      </button>
      {open && (
        <>
          <h4>С чего начать</h4>
          <ol>
            {STEPS.map((s) => (
              <li key={s}>{s}</li>
            ))}
          </ol>
          <h4>Управление</h4>
          <table>
            <tbody>
              {ROWS.map(([k, v]) => (
                <tr key={k}>
                  <td>
                    <kbd>{k}</kbd>
                  </td>
                  <td>{v}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </>
      )}
    </div>
  );
}
